import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createCharacterState, applyStatePatch, createMemoryRecord, createPermissionRequest, permissionAllows, createEventBus, buildWorkspace, arbitrate } from "../../core/index.mjs";
import { createSkillRegistry } from "../../skills/runtime/index.mjs";
import { createLLMProvider } from "../../providers/llm/interface.mjs";
import { createTTSProvider } from "../../providers/tts/interface.mjs";
import { createSTTProvider } from "../../providers/stt/interface.mjs";
import { createAvatarProvider } from "../../providers/avatar/interface.mjs";

const cases = [];
const check = (name, fn) => { try { const value = fn(); cases.push({ name, passed: value === true }); } catch (error) { cases.push({ name, passed: false, error: String(error?.message || error) }); } };
check("state_default_idle", () => createCharacterState().state.activity === "idle");
const state0 = createCharacterState({ characterId: "bench" });
const state1 = applyStatePatch(state0, { activity: "thinking" }, { type: "bench.thinking" });
check("state_patch_revision", () => state1.revision === 1);
check("state_activity_contract", () => state1.state.activity === "thinking");
check("state_restart_serialization", () => JSON.parse(JSON.stringify(state1)).state.activity === "thinking");
check("memory_allows_episodic", () => createMemoryRecord({ layer: "episodic", content: "evidence" }).layer === "episodic");
check("memory_rejects_unknown_layer", () => { try { createMemoryRecord({ layer: "unknown", content: "x" }); return false; } catch { return true; } });
const pending = createPermissionRequest({ capability: "private.files.read", scope: "data/private/demo.txt" });
check("permission_pending_status", () => pending.status === "pending_user_confirmation");
check("permission_pending_denied", () => permissionAllows({ grant: pending, capability: pending.capability, scope: pending.scope }) === false);
check("permission_scope_match", () => permissionAllows({ grant: { ...pending, status: "approved" }, capability: pending.capability, scope: "data/private/demo.txt" }));
check("permission_scope_escape_denied", () => permissionAllows({ grant: { ...pending, status: "approved", scope: "data/private/demo.txt" }, capability: pending.capability, scope: "data/private/other.txt" }) === false);
const bus = createEventBus({ maxEvents: 2 });
bus.emit({ type: "one" }); bus.emit({ type: "two" }); bus.emit({ type: "three" });
check("event_bus_bounded", () => bus.recent(10).length === 2);
const workspace = buildWorkspace({ events: Array.from({ length: 10 }, (_, i) => ({ type: "observation", summary: `e${i}` })), memories: Array.from({ length: 12 }, (_, i) => ({ id: i })) });
check("attention_workspace_events_bound", () => workspace.salientEvents.length <= 6);
check("conscious_memory_bound", () => workspace.retrievedMemory.length === 8);
check("attention_gate_flag", () => workspace.attentionGate.enabled === true);
check("permission_veto_final", () => arbitrate({ drive: 1, feasibility: 1, goalRelevance: 1, safetyPermission: 1, permissionVeto: true }).allowed === false);
const registry = createSkillRegistry(); registry.register({ id: "bench-skill" }); registry.validate("bench-skill", { passed: true });
check("skill_candidate_validated", () => registry.get("bench-skill").status === "validated");
check("skill_promotion_requires_confirmation", () => { try { registry.promote("bench-skill", { userConfirmed: false, actor: "agent" }); return false; } catch { return true; } });
registry.promote("bench-skill", { userConfirmed: true, actor: "user-confirmation" });
check("skill_promotion_confirmed", () => registry.get("bench-skill").status === "approved");
registry.rollback("bench-skill", { userConfirmed: true, actor: "user-confirmation" });
check("skill_rollback", () => registry.get("bench-skill").status === "rolled_back");
check("llm_provider_contract", () => createLLMProvider({ id: "bench", complete: async () => ({}) }).localOnly === true);
check("tts_provider_contract", () => createTTSProvider({ id: "bench", synthesize: async () => new Uint8Array() }).localOnly === true);
check("stt_provider_contract", () => createSTTProvider({ id: "bench", transcribe: async () => "" }).localOnly === true);
check("avatar_provider_contract", () => createAvatarProvider({ id: "bench", play: async () => {} }).states.includes("speaking"));

const failed = cases.filter((item) => !item.passed);
const report = { benchmark: "XiaoyaBench-v0", project: "Xiaoya Framework", status: failed.length ? "FAIL" : "PASS", total: cases.length, passed: cases.length - failed.length, failed, unauthorizedAction: 0, localOnly: true, downloads: 0, uploads: 0, finishedAt: new Date().toISOString() };
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "results", "latest.json");
await fs.mkdir(path.dirname(output), { recursive: true }); await fs.writeFile(output, `${JSON.stringify(report, null, 2)}\n`, "utf8");
console.log(JSON.stringify(report, null, 2));
process.exit(failed.length ? 1 : 0);
